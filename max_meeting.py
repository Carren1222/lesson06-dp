# -*- coding: utf-8 -*-
# ============================================================
# 课堂练习（第6课）：会议室安排 —— 区间调度的贪心算法
#
# 背景：只有一间会议室，同一时间只能开一场会。
#       每场会议有开始/结束时间，问最多能安排几场？
# 策略（贪心）：每次都选「结束最早」的会议——
#       谁先腾出会议室，就先安排谁，给后面的会留足时间。
# 小规则：上一场 5 点结束、下一场 5 点开始，算不冲突（背靠背）。
# ============================================================

def max_meetings(meetings):
    """贪心选会：meetings 是 (会议名, 开始, 结束) 的列表。

    返回 (最多场数, 入选会议列表)。
    过程中打印每一步的取舍，不懂代码也能看懂策略。
    """
    # 第 1 步：按「结束时间」从早到晚排队（贪心的核心就这一行）
    ordered = sorted(meetings, key=lambda m: m[2])

    chosen = []   # 最终入选的会议
    free_at = 0   # 会议室几点起空闲（一开始 0 点就空着）

    print("  (按结束时间从早到晚, 逐个判断:)")
    for name, start, end in ordered:
        if start >= free_at:
            # 开始时间不早于空闲时刻 -> 不撞车, 安排!
            chosen.append((name, start, end))
            free_at = end
            print("    [选] %s  %d~%d点  (开完到 %d 点, 会议室随即空出)"
                  % (name, start, end, end))
        else:
            # 会议室还没空它就想开 -> 时间冲突, 只能放弃
            print("    [舍] %s  %d~%d点  (会议室 %d 点才有空, 它 %d 点就开始)"
                  % (name, start, end, free_at, start))
    return len(chosen), chosen

def show_result(title, meetings):
    """用大白话汇报一组测试的结果。"""
    print(title)
    n, chosen = max_meetings(meetings)
    print("  ==> 报名 %d 场, 最多能安排 %d 场:" % (len(meetings), n))
    for name, start, end in chosen:
        print("        %d点 ~ %d点  %s" % (start, end, name))
    print()

